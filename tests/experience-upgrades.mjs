import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),ts=require('typescript');
function load(path){const scope={exports:{},Date,Intl,Map,TextEncoder};vm.runInNewContext(ts.transpile(fs.readFileSync(new URL(path,import.meta.url),'utf8'),{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}),scope);return scope.exports;}
const {eventCalendar}=load('../src/lib/event-calendar.ts');
const event={id:'abc',title:'Church, family; gathering',description:'First line\r\nSecond line',location:'Lusaka',event_date:'2026-12-31',event_end_date:'2027-01-02'};
const text=eventCalendar(event);
assert.ok(text.includes('DTSTART;VALUE=DATE:20261231\r\n'));
assert.ok(text.includes('DTEND;VALUE=DATE:20270103\r\n'));
assert.ok(text.includes('SUMMARY:Church\\, family\\; gathering'));
assert.ok(text.includes('DESCRIPTION:First line\\nSecond line'));
assert.ok(eventCalendar({...event,event_end_date:null}).includes('DTEND;VALUE=DATE:20270101'));
assert.equal(eventCalendar({...event,event_date:'2026-02-30'}),null);
assert.equal(eventCalendar({...event,event_end_date:'2026-01-01'}),null);
const long=eventCalendar({...event,title:'🙏é'.repeat(100)});
for(const line of long.split('\r\n'))assert.ok(Buffer.byteLength(line)<=75,'Fold UTF-8 calendar lines at 75 bytes');
assert.ok(long.replace(/\r\n /g,'').includes('SUMMARY:'+'🙏é'.repeat(100)));
const {localDateToday}=load('../src/lib/care-requests.ts');
assert.equal(localDateToday(new Date('2026-12-31T22:30:00Z')),'2027-01-01');
assert.equal(localDateToday(new Date('2026-10-15T21:59:00Z')),'2026-10-15');
const {careAgenda}=load('../src/lib/care-agenda.ts');
const base={name:'Test',kind:'other',status:'contacted',requested_date:null,confirmed_date:null,confirmed_time:null};
const requests=[{...base,id:'due'},{...base,id:'done'},{...base,id:'closed',status:'closed'},{...base,id:'appointment',kind:'appointment',status:'approved',confirmed_date:'2026-10-15',confirmed_time:'10:00:00'},{...base,id:'pending',kind:'appointment',status:'pending',requested_date:'2026-10-15'},{...base,id:'visit',kind:'visit',requested_date:'2026-10-22'},{...base,id:'future',kind:'visit',requested_date:'2026-10-23'}];
const followups=[{id:'1',request_id:'due',stage:'contacted',next_followup:'2026-10-10',created_at:'2026-10-09'},{id:'2',request_id:'done',stage:'completed',next_followup:null,created_at:'2026-10-15'},{id:'1',request_id:'done',stage:'contacted',next_followup:'2026-10-10',created_at:'2026-10-09'},{id:'3',request_id:'closed',stage:'contacted',next_followup:'2026-10-10',created_at:'2026-10-09'}];
const entries=careAgenda(requests,followups,'2026-10-15');
assert.deepEqual(Array.from(entries,e=>e.id),['due','appointment','visit']);
assert.equal(entries[0].overdue,true);
assert.equal(entries[1].time,'10:00');
assert.equal(entries[2].overdue,false);
assert.equal(careAgenda([{...base,id:'prayer',kind:'prayer'}],[{...followups[0],request_id:'prayer'}],'2026-10-15').length,0);
console.log('Passed calendar date ranges, escaping, UTF-8 folding, Lusaka date boundaries, and agenda reminder checks.');
